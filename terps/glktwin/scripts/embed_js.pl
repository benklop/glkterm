#!/usr/bin/env perl
# Generate a C source file that embeds JS files as string literals.
# Usage: embed_js.pl <js_dir> <output.c>
# Reads js_dir/jquery.min.js, js_dir/formats/*.js and outputs C declarations.

use strict;
use warnings;
use File::Spec;

my ($js_dir, $out_path) = @ARGV;
die "Usage: $0 <js_dir> <output.c>\n" unless $js_dir && $out_path;

my %files = (
    'jquery' => 'jquery.min.js',
);
my @format_files = glob(File::Spec->catfile($js_dir, 'formats', '*.js'));
for my $path (@format_files) {
    my $base = $path;
    $base =~ s/.*[\/\\]formats[\/\\]//;
    $base =~ s/\.js$//;
    $files{"format_$base"} = File::Spec->catfile('formats', $base . '.js');
}

open my $out, '>', $out_path or die "Cannot write $out_path: $!";
print $out "/* Auto-generated by embed_js.pl - do not edit */\n";
print $out "#include <stddef.h>\n\n";

while (my ($var, $rel) = each %files) {
    my $full = File::Spec->catfile($js_dir, $rel);
    $var =~ s/[^a-zA-Z0-9_]/_/g;
    my $content = '';
    if (open my $fh, '<', $full) {
        local $/;
        $content = <$fh>;
        $content =~ s/\r\n?/\n/g;
        close $fh;
    }
    my $len = length($content);
    $content =~ s/\\/\\\\/g;
    $content =~ s/"/\\"/g;
    $content =~ s/\n/\\n\"\n    \"/g;
    print $out "const char glktwin_js_${var}[] =\n    \"$content\";\n";
    print $out "const size_t glktwin_js_${var}_len = $len;\n\n";
}

close $out;
